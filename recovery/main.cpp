static bool readJsonFile(const char * path, JsonDocument & doc) {
    File file = LittleFS.open(path, "r");
    if (!file) {
        return false;
    }
    const DeserializationError error = deserializeJson(doc, file);
    file.close();
    if (error) {
        LOG("Failed to parse %s: %s", path, error.c_str());
        return false;
    }
    return true;
}

static IPAddress parseIP(JsonVariantConst value, const char * fallback) {
    IPAddress ip;
    if (!ip.fromString(value | fallback)) {
        ip.fromString(fallback);
    }
    return ip;
}

static void loadSettings() {
    // never format the filesystem, it holds the EMS-ESP settings
    const bool mounted = LittleFS.begin(false);
    LOG("LittleFS %s", mounted ? "mounted" : "not available, using factory settings");

    JsonDocument doc;
    if (mounted && readJsonFile("/config/apSettings.json", doc)) {
        settings.ap_ssid     = doc["ssid"] | FACTORY_AP_SSID;
        settings.ap_password = doc["password"] | FACTORY_AP_PASSWORD;
        settings.ap_channel  = doc["channel"] | FACTORY_AP_CHANNEL;
    }
    settings.ap_ip      = parseIP(doc["local_ip"], FACTORY_AP_LOCAL_IP);
    settings.ap_gateway = parseIP(doc["gateway_ip"], FACTORY_AP_GATEWAY_IP);
    settings.ap_subnet  = parseIP(doc["subnet_mask"], FACTORY_AP_SUBNET_MASK);

    doc.clear();
    if (mounted && readJsonFile("/config/networkSettings.json", doc)) {
        settings.wifi_ssid     = doc["ssid"] | FACTORY_WIFI_SSID;
        settings.wifi_password = doc["password"] | FACTORY_WIFI_PASSWORD;
        settings.hostname      = doc["hostname"] | FACTORY_NETWORK_HOSTNAME;
        settings.eth_10mbit    = doc["eth_10mbit"] | false;
        settings.local_ip.fromString(doc["local_ip"] | "");
        settings.gateway_ip.fromString(doc["gateway_ip"] | "");
        settings.subnet_mask.fromString(doc["subnet_mask"] | "");
        settings.dns_ip_1.fromString(doc["dns_ip_1"] | "");
        settings.dns_ip_2.fromString(doc["dns_ip_2"] | "");
        settings.static_ip = (doc["static_ip_config"] | false) && settings.local_ip != IPAddress();
    }

    // the Ethernet PHY settings come from the board profile, stored with the EMS-ESP application settings
    doc.clear();
    if (mounted && readJsonFile("/config/emsespSettings.json", doc)) {
        settings.phy_type       = doc["phy_type"] | 0;
        settings.eth_power      = doc["eth_power"] | -1;
        settings.eth_phy_addr   = doc["eth_phy_addr"] | 0;
        settings.eth_clock_mode = doc["eth_clock_mode"] | 0;
    }

    doc.clear();
    if (mounted && readJsonFile("/config/securitySettings.json", doc)) {
        for (JsonObject user : doc["users"].as<JsonArray>()) {
            if (user["admin"] | false) {
                settings.admins.push_back({user["username"] | "", user["password"] | ""});
            }
        }
    }
    if (settings.admins.empty()) {
        settings.admins.push_back({FACTORY_ADMIN_USERNAME, FACTORY_ADMIN_PASSWORD});
    }

    if (mounted) {
        LittleFS.end();
    }
}

