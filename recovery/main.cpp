static String generateToken() {
    uint8_t bytes[16];
    esp_fill_random(bytes, sizeof(bytes));
    String token;
    token.reserve(sizeof(bytes) * 2);
    for (uint8_t b : bytes) {
        char hex[3];
        snprintf(hex, sizeof(hex), "%02x", b);
        token += hex;
    }
    return token;
}

static bool isAuthorized(AsyncWebServerRequest * request) {
    if (session_token.isEmpty() || !request->hasHeader("Authorization")) {
        return false;
    }
    return request->header("Authorization") == "Bearer " + session_token;
}

