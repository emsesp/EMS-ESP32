static bool openNvs(Preferences & nvs, bool readOnly) {
    if (esp_partition_find_first(ESP_PARTITION_TYPE_DATA, ESP_PARTITION_SUBTYPE_DATA_NVS, "nvs1")) {
        return nvs.begin(NVS_NAMESPACE, readOnly, "nvs1");
    }
    return nvs.begin(NVS_NAMESPACE, readOnly, "nvs");
}

static const char * otaStateName(esp_ota_img_states_t state) {
    switch (state) {
    case ESP_OTA_IMG_NEW:
        return "new";
    case ESP_OTA_IMG_PENDING_VERIFY:
        return "pending";
    case ESP_OTA_IMG_VALID:
        return "valid";
    case ESP_OTA_IMG_INVALID:
        return "invalid";
    case ESP_OTA_IMG_ABORTED:
        return "aborted";
    default:
        return "";
    }
}

static const char * resetReasonName(esp_reset_reason_t reason) {
    switch (reason) {
    case ESP_RST_POWERON:
        return "power_on";
    case ESP_RST_EXT:
        return "external";
    case ESP_RST_SW:
        return "software";
    case ESP_RST_PANIC:
        return "panic";
    case ESP_RST_INT_WDT:
    case ESP_RST_TASK_WDT:
    case ESP_RST_WDT:
        return "watchdog";
    case ESP_RST_BROWNOUT:
        return "brownout";
    default:
        return "other";
    }
}

// one-shot, so a later restart into the recovery doesn't show a stale reason
static void loadRecoveryReason() {
    Preferences nvs;
    if (!openNvs(nvs, false)) {
        return;
    }
    if (nvs.isKey(NVS_REASON)) {
        recovery_reason = nvs.getString(NVS_REASON);
        nvs.remove(NVS_REASON);
    }
    nvs.end();
}

static void loadPartitions() {
    partitions.clear();

    Preferences nvs;
    const bool  has_nvs = openNvs(nvs, true);

    const esp_partition_t *  running = esp_ota_get_running_partition();
    esp_partition_iterator_t it      = esp_partition_find(ESP_PARTITION_TYPE_APP, ESP_PARTITION_SUBTYPE_ANY, nullptr);
    for (; it != nullptr; it = esp_partition_next(it)) {
        const esp_partition_t * part = esp_partition_get(it);

        PartitionInfo info;
        info.label      = part->label;
        info.factory    = part->subtype == ESP_PARTITION_SUBTYPE_APP_FACTORY;
        info.address      = part->address;
        info.size         = part->size;
        info.image_size   = 0;
        info.install_date = 0;

        esp_image_metadata_t meta = {};
        esp_partition_pos_t  pos  = {.offset = part->address, .size = part->size};
        info.valid                = esp_image_verify(ESP_IMAGE_VERIFY_SILENT, &pos, &meta) == ESP_OK;
        if (info.valid) {
            info.image_size = meta.image_len;
        }

        esp_ota_img_states_t state;
        if (!info.factory && esp_ota_get_state_partition(part, &state) == ESP_OK) {
            info.ota_state = otaStateName(state);
        }

        if (part == running) {
            info.version = RECOVERY_VERSION;
        } else if (info.valid) {
            // EMS-ESP stores the version and install date of each partition in NVS, keyed by the label
            if (has_nvs && nvs.isKey(part->label)) {
                info.version      = nvs.getString(part->label);
                info.install_date = nvs.getULong(("d_" + info.label).c_str(), 0);
            }
            esp_app_desc_t desc;
            if (info.version.isEmpty() && esp_ota_get_partition_description(part, &desc) == ESP_OK) {
                info.version = desc.version;
            }
        }

        partitions.push_back(info);
    }
    esp_partition_iterator_release(it);

    if (has_nvs) {
        nvs.end();
    }
}

static const esp_partition_t * findAppPartition(const char * label) {
    return esp_partition_find_first(ESP_PARTITION_TYPE_APP, ESP_PARTITION_SUBTYPE_ANY, label);
}

static bool failedToStart(const PartitionInfo & info) {
    return info.ota_state == "aborted" || info.ota_state == "invalid";
}

// An empty OTA partition if there is one, then one whose firmware failed to start, so a working firmware
// is kept. Otherwise the one with the oldest install date, keeping the most recent firmware as a fallback.
static const esp_partition_t * defaultUploadTarget() {
    const PartitionInfo * best = nullptr;
    auto                  rank = [](const PartitionInfo & info) { return !info.valid ? 0 : failedToStart(info) ? 1 : 2; };
    for (const auto & info : partitions) {
        if (info.factory) {
            continue;
        }
        if (best == nullptr || rank(info) < rank(*best) || (rank(info) == rank(*best) && info.install_date < best->install_date)) {
            best = &info;
        }
    }
    return best ? findAppPartition(best->label.c_str()) : esp_ota_get_next_update_partition(nullptr);
}

static const esp_partition_t * uploadTarget(AsyncWebServerRequest * request) {
    if (!request->hasParam("partition")) {
        return defaultUploadTarget();
    }
    const esp_partition_t * part = findAppPartition(request->getParam("partition")->value().c_str());
    if (part == nullptr || part->subtype == ESP_PARTITION_SUBTYPE_APP_FACTORY || part == esp_ota_get_running_partition()) {
        return nullptr;
    }
    return part;
}

// tells EMS-ESP it's running a newly flashed firmware, and drops the now stale version info for that partition
static void markFreshFirmware(const String & label) {
    Preferences nvs;
    if (!openNvs(nvs, false)) {
        return;
    }
    nvs.putBool(NVS_FRESH_FW, true);
    if (!label.isEmpty()) {
        nvs.remove(label.c_str());
        nvs.remove(("d_" + label).c_str());
    }
    nvs.end();
}

