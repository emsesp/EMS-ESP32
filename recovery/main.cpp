static void joinWiFi() {
    wifi_join_at = 0;
    if (settings.wifi_ssid.isEmpty()) {
        return;
    }
    WiFi.mode(WIFI_AP_STA);
    if (settings.static_ip) {
        WiFi.config(settings.local_ip, settings.gateway_ip, settings.subnet_mask, settings.dns_ip_1, settings.dns_ip_2);
    }
    WiFi.begin(settings.wifi_ssid.c_str(), settings.wifi_password.c_str());
    wifi_started = true;
    LOG("Connecting to WiFi %s%s", settings.wifi_ssid.c_str(), settings.static_ip ? (" with IP " + settings.local_ip.toString()).c_str() : "");
}

// same bring-up as Network::startEthernet() in src/core/network.cpp
static bool startEthernet() {
#if CONFIG_IDF_TARGET_ESP32
    if (settings.phy_type == 0) {
        return false;
    }
    const auto clock = static_cast<eth_clock_mode_t>(settings.eth_clock_mode);
    if (ESP.getPsramSize() && (clock == ETH_CLOCK_GPIO16_OUT || clock == ETH_CLOCK_GPIO17_OUT)) {
        LOG("Ethernet clock mode %d conflicts with PSRAM, Ethernet disabled", settings.eth_clock_mode);
        eth_state = "disabled";
        return false;
    }

    // reset the PHY, it doesn't always start after a warm boot
    if (settings.eth_power != -1) {
        pinMode(settings.eth_power, OUTPUT);
        digitalWrite(settings.eth_power, LOW);
        delay(500);
        digitalWrite(settings.eth_power, HIGH);
    }

    if (settings.eth_10mbit) {
        ETH.setAutoNegotiation(false);
        ETH.setLinkSpeed(10);
        ETH.setFullDuplex(false);
    }

    const eth_phy_type_t type = settings.phy_type == 1 ? ETH_PHY_LAN8720 : settings.phy_type == 2 ? ETH_PHY_TLK110 : ETH_PHY_RTL8201;
    if (!ETH.begin(type, settings.eth_phy_addr, 23, 18, settings.eth_power, clock)) {
        LOG("Ethernet failed to start, no PHY found");
        eth_state = "failed";
        return false;
    }
    if (settings.static_ip) {
        ETH.config(settings.local_ip, settings.gateway_ip, settings.subnet_mask, settings.dns_ip_1, settings.dns_ip_2);
    }
    eth_state = "started";
    LOG("Ethernet started%s", settings.static_ip ? (" with IP " + settings.local_ip.toString()).c_str() : "");
    return true;
#else
    return false;
#endif
}

static bool ethConnected() {
#if CONFIG_IDF_TARGET_ESP32
    return strcmp(eth_state, "started") == 0 && ETH.hasIP();
#else
    return false;
#endif
}

static void startNetwork() {
    WiFi.persistent(false);
    WiFi.setHostname(settings.hostname.c_str()); // also the default for the Ethernet interface
    WiFi.mode(WIFI_AP);

    // max SSID length is 32
    ap_ssid = settings.ap_ssid.substring(0, 23) + "-recovery";
    WiFi.softAPConfig(settings.ap_ip, settings.ap_gateway, settings.ap_subnet);
    // WPA2 needs at least 8 characters, otherwise fall back to the factory password
    const String & ap_password = settings.ap_password.length() >= 8 ? settings.ap_password : String(FACTORY_AP_PASSWORD);
    WiFi.softAP(ap_ssid.c_str(), ap_password.c_str(), settings.ap_channel);
    LOG("Access point %s started on %s", ap_ssid.c_str(), WiFi.softAPIP().toString().c_str());

    // like EMS-ESP, Ethernet first and WiFi only if Ethernet doesn't get an address, as both share a static IP
    if (startEthernet()) {
        wifi_join_at = millis() + ETH_WAIT_MS;
    } else {
        joinWiFi();
    }

    dnsServer.start(53, "*", WiFi.softAPIP());

    if (MDNS.begin(settings.hostname.c_str())) {
        MDNS.addService("http", "tcp", 80);
    }
}

static void startWebServer() {
    server.on("/rest/recovery/status", HTTP_GET, handleStatus);
    server.on("/rest/recovery/restart", HTTP_POST, handleRestart);
    server.on("/rest/uploadFile", HTTP_POST, handleUploadComplete, handleUpload);
    server.addHandler(new AsyncCallbackJsonWebHandler("/rest/signIn", handleSignIn));
    server.addHandler(new AsyncCallbackJsonWebHandler("/rest/recovery/boot", handleSetBoot));
    server.addHandler(new StaticContentHandler()); // must be last
    server.begin();
}

void setup() {
    Serial.begin(115200);
    LOG("EMS-ESP Recovery v%s", RECOVERY_VERSION);

    loadSettings();
    loadRecoveryReason();
    loadPartitions();
    startNetwork();
    startWebServer();
}

void loop() {
    dnsServer.processNextRequest();

    static bool was_connected = false;
    if (WiFi.isConnected() != was_connected) {
        was_connected = WiFi.isConnected();
        if (was_connected) {
            LOG("WiFi connected, IP %s", WiFi.localIP().toString().c_str());
        }
    }

#if CONFIG_IDF_TARGET_ESP32
    static bool eth_was_connected = false;
    if (ethConnected() != eth_was_connected) {
        eth_was_connected = ethConnected();
        if (eth_was_connected) {
            LOG("Ethernet connected, IP %s", ETH.localIP().toString().c_str());
        }
    }
#endif

    if (wifi_join_at && (int32_t)(millis() - wifi_join_at) >= 0) {
        if (ethConnected()) {
            wifi_join_at = 0;
        } else {
            LOG("No Ethernet connection");
            joinWiFi();
        }
    }

    if (restart_at && (int32_t)(millis() - restart_at) >= 0) {
        ESP.restart();
    }

    delay(10);
}
